// scripts/set-version.mjs 시험 — Node 내장 시험 도구: `node --test scripts/set-version.test.mjs`
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { after, beforeEach, describe, test } from "node:test";
import { fileURLToPath } from "node:url";

import { isValidVersion, readVersions, run, setVersion, versionMismatches } from "./set-version.mjs";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCRIPT = join(REPO, "scripts", "set-version.mjs");

const PACKAGE_JSON = `{
  "name": "nyanitor",
  "private": true,
  "version": "0.1.0",
  "scripts": {
    "version:set": "node scripts/set-version.mjs"
  },
  "dependencies": {
    "version": "^0.1.0"
  }
}
`;

const PACKAGE_LOCK = `{
  "name": "nyanitor",
  "version": "0.1.0",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {
      "name": "nyanitor",
      "version": "0.1.0",
      "dependencies": {
        "react": "^19.1.0"
      }
    },
    "node_modules/react": {
      "version": "0.1.0",
      "resolved": "https://registry.npmjs.org/react/-/react-0.1.0.tgz"
    }
  }
}
`;

const CARGO_TOML = `[package]
name = "nyanitor"
version = "0.1.0"
description = "한글 설명 — 그대로 남아야 한다"
edition = "2024"

[dependencies]
serde = { version = "1", features = ["derive"] }

[dependencies.other]
version = "0.1.0"
`;

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "aaa"
version = "0.1.0"

[[package]]
name = "nyanitor"
version = "0.1.0"
dependencies = [
 "aaa",
]

[[package]]
name = "nyanitor-extra"
version = "0.1.0"
`;

const FILES = {
  "package.json": PACKAGE_JSON,
  "package-lock.json": PACKAGE_LOCK,
  "src-tauri/Cargo.toml": CARGO_TOML,
  "src-tauri/Cargo.lock": CARGO_LOCK,
};

const roots = [];
function makeRoot(files = FILES) {
  const root = mkdtempSync(join(tmpdir(), "nyanitor-setver-"));
  roots.push(root);
  mkdirSync(join(root, "src-tauri"));
  for (const [file, text] of Object.entries(files)) {
    writeFileSync(join(root, file), text);
  }
  return root;
}
const read = (root, file) => readFileSync(join(root, file), "utf8");
const snapshot = (root) => Object.fromEntries(Object.keys(FILES).map((f) => [f, read(root, f)]));

/** 바뀐 줄 번호 목록 (줄 수는 같아야 한다). */
function changedLines(before, after) {
  const a = before.split("\n");
  const b = after.split("\n");
  assert.equal(b.length, a.length, "줄 수가 달라졌다");
  return a.flatMap((line, i) => (line === b[i] ? [] : [i + 1]));
}

after(() => {
  for (const root of roots) rmSync(root, { recursive: true, force: true });
});

describe("isValidVersion", () => {
  test("SemVer 는 받는다", () => {
    for (const v of ["0.2.0", "0.2.0-beta.1", "1.0.0-rc.1", "10.20.30", "0.1.1-alpha", "1.2.3-0.x-y"]) {
      assert.equal(isValidVersion(v), true, v);
    }
  });

  test("v 접두 · 빈 값 · 공백 · 모자란 자리 · 앞 0 · 빌드 표시는 거절한다", () => {
    for (const v of [
      "v0.2.0",
      "",
      " ",
      " 0.2.0",
      "0.2.0 ",
      "0.2.0\n",
      "0.2",
      "0.2.0.1",
      "01.2.3",
      "0.2.0-",
      "0.2.0-01",
      "0.2.0-beta..1",
      "0.2.0+build.1",
      "latest",
      "../0.2.0",
    ]) {
      assert.equal(isValidVersion(v), false, JSON.stringify(v));
    }
  });

  test("문자열이 아니면 거절한다", () => {
    for (const v of [undefined, null, 2, {}, ["0.2.0"]]) {
      assert.equal(isValidVersion(v), false);
    }
  });
});

describe("setVersion", () => {
  let root;
  beforeEach(() => {
    root = makeRoot();
  });

  test("판이 적힌 줄만 바꾼다 — 다른 패키지 · 같은 값의 다른 줄은 그대로", () => {
    const before = snapshot(root);
    const files = setVersion(root, "0.2.0-beta.1");
    assert.equal(files.length, 4);
    const now = snapshot(root);

    assert.deepEqual(changedLines(before["package.json"], now["package.json"]), [4]);
    assert.deepEqual(changedLines(before["package-lock.json"], now["package-lock.json"]), [3, 9]);
    assert.deepEqual(changedLines(before["src-tauri/Cargo.toml"], now["src-tauri/Cargo.toml"]), [3]);
    assert.deepEqual(changedLines(before["src-tauri/Cargo.lock"], now["src-tauri/Cargo.lock"]), [10]);

    assert.equal(JSON.parse(now["package.json"]).version, "0.2.0-beta.1");
    assert.equal(JSON.parse(now["package.json"]).dependencies.version, "^0.1.0");
    const lock = JSON.parse(now["package-lock.json"]);
    assert.equal(lock.version, "0.2.0-beta.1");
    assert.equal(lock.packages[""].version, "0.2.0-beta.1");
    assert.equal(lock.packages["node_modules/react"].version, "0.1.0");
    assert.match(now["src-tauri/Cargo.lock"], /name = "aaa"\nversion = "0.1.0"/);
    assert.match(now["src-tauri/Cargo.lock"], /name = "nyanitor-extra"\nversion = "0.1.0"/);
    assert.match(now["src-tauri/Cargo.toml"], /\[dependencies\.other\]\nversion = "0.1.0"/);
    assert.match(now["src-tauri/Cargo.toml"], /한글 설명 — 그대로 남아야 한다/);
  });

  test("같은 판으로 다시 불러도 안전하다 (글이 같다)", () => {
    setVersion(root, "0.2.0");
    const once = snapshot(root);
    setVersion(root, "0.2.0");
    assert.deepEqual(snapshot(root), once);
  });

  test("판을 바꿨다가 되돌리면 처음 글과 바이트까지 같다", () => {
    const before = snapshot(root);
    setVersion(root, "9.9.9");
    setVersion(root, "0.1.0");
    assert.deepEqual(snapshot(root), before);
  });

  test("CRLF 파일은 CRLF 로, LF 파일은 LF 로 남는다", () => {
    const crlf = Object.fromEntries(
      Object.entries(FILES).map(([file, text]) => [file, text.replaceAll("\n", "\r\n")]),
    );
    const crlfRoot = makeRoot(crlf);
    setVersion(crlfRoot, "0.2.0");
    const now = snapshot(crlfRoot);
    for (const [file, text] of Object.entries(now)) {
      assert.equal(text.replace(/\r\n/g, "").includes("\n"), false, `${file}: LF 가 섞였다`);
      assert.equal(text.replace(/\r\n/g, "").includes("\r"), false, `${file}: CR 이 남았다`);
      assert.match(text, /0\.2\.0/);
    }
    // 위 root 는 LF 파일 — LF 만 있다.
    setVersion(root, "0.2.0");
    for (const file of Object.keys(FILES)) assert.equal(read(root, file).includes("\r"), false);
  });

  test("SemVer 가 아니면 아무 파일도 안 바꾸고 던진다", () => {
    const before = snapshot(root);
    for (const v of ["v0.2.0", "", "0.2", undefined]) {
      assert.throws(() => setVersion(root, v), /SemVer/);
    }
    assert.deepEqual(snapshot(root), before);
  });

  test("한 파일에서 판 줄을 못 찾으면 하나도 안 바꾼다", () => {
    const broken = makeRoot({ ...FILES, "src-tauri/Cargo.lock": CARGO_LOCK.replace('name = "nyanitor"', 'name = "other"') });
    const before = snapshot(broken);
    assert.throws(() => setVersion(broken, "0.2.0"), /Cargo\.lock.*찾지 못했다/);
    assert.deepEqual(snapshot(broken), before);
  });

  test("판 줄이 둘이면 (모호하면) 하나도 안 바꾼다", () => {
    const twice = makeRoot({
      ...FILES,
      "src-tauri/Cargo.lock": `${CARGO_LOCK}\n[[package]]\nname = "nyanitor"\nversion = "0.1.0"\n`,
    });
    const before = snapshot(twice);
    assert.throws(() => setVersion(twice, "0.2.0"), /Cargo\.lock.*2곳/);
    assert.deepEqual(snapshot(twice), before);
  });

  test("Cargo.toml 이 workspace 판을 쓰면 (version 줄 없음) 하나도 안 바꾼다", () => {
    const ws = makeRoot({
      ...FILES,
      "src-tauri/Cargo.toml": CARGO_TOML.replace('version = "0.1.0"\ndescription', "version.workspace = true\ndescription"),
    });
    const before = snapshot(ws);
    assert.throws(() => setVersion(ws, "0.2.0"), /Cargo\.toml/);
    assert.deepEqual(snapshot(ws), before);
  });

  test("파일이 없으면 던지고 나머지는 그대로", () => {
    const missing = makeRoot({ "package.json": PACKAGE_JSON });
    const before = read(missing, "package.json");
    assert.throws(() => setVersion(missing, "0.2.0"));
    assert.equal(read(missing, "package.json"), before);
  });

  test("쓰다가 셋째 파일에서 실패하면 앞서 쓴 파일을 되돌린다", () => {
    const before = snapshot(root);
    let calls = 0;
    const io = {
      readFileSync,
      writeFileSync(path, text) {
        calls += 1;
        if (calls === 3) throw new Error("디스크가 가득 찼다");
        writeFileSync(path, text);
      },
    };
    assert.throws(() => setVersion(root, "0.2.0", io), /디스크가 가득 찼다.*모두 되돌렸다/);
    assert.deepEqual(snapshot(root), before);
  });

  test("되돌리기도 실패하면 어느 파일인지 알려 준다", () => {
    let calls = 0;
    const io = {
      readFileSync,
      writeFileSync(path, text) {
        calls += 1;
        if (calls === 2 || calls === 3) throw new Error("쓰기 실패");
        writeFileSync(path, text);
      },
    };
    assert.throws(() => setVersion(root, "0.2.0", io), /되돌리지 못한 파일/);
  });
});

describe("readVersions · versionMismatches", () => {
  test("판 줄 다섯 곳을 읽는다", () => {
    const root = makeRoot();
    assert.deepEqual(readVersions(root), {
      "package.json": ["0.1.0"],
      "package-lock.json": ["0.1.0", "0.1.0"],
      [join("src-tauri", "Cargo.toml")]: ["0.1.0"],
      [join("src-tauri", "Cargo.lock")]: ["0.1.0"],
    });
    assert.deepEqual(versionMismatches(root, "0.1.0"), []);
  });

  test("어긋난 곳을 모두 알려 준다", () => {
    const root = makeRoot();
    const bad = versionMismatches(root, "0.2.0");
    assert.equal(bad.length, 5);
    setVersion(root, "0.2.0");
    assert.deepEqual(versionMismatches(root, "0.2.0"), []);
    writeFileSync(join(root, "src-tauri", "Cargo.toml"), CARGO_TOML);
    assert.equal(versionMismatches(root, "0.2.0").length, 1);
  });
});

describe("run (명령줄)", () => {
  const sink = () => {
    const chunks = [];
    return { write: (s) => chunks.push(s), text: () => chunks.join("") };
  };

  test("판을 주면 바꾸고 0", () => {
    const root = makeRoot();
    const out = sink();
    const err = sink();
    assert.equal(run(["0.2.0"], root, out, err), 0);
    assert.match(out.text(), /0\.2\.0/);
    assert.equal(err.text(), "");
    assert.deepEqual(versionMismatches(root, "0.2.0"), []);
  });

  test("인자가 없거나 둘이거나 v 가 붙었으면 2, 파일은 그대로", () => {
    const root = makeRoot();
    const before = snapshot(root);
    for (const argv of [[], ["0.2.0", "0.3.0"], ["v0.2.0"], [""], ["--check"], ["--check", "v0.2.0"]]) {
      const err = sink();
      assert.equal(run(argv, root, sink(), err), 2, JSON.stringify(argv));
      assert.notEqual(err.text(), "");
    }
    assert.deepEqual(snapshot(root), before);
  });

  test("--check 는 바꾸지 않고 맞으면 0 · 다르면 1", () => {
    const root = makeRoot();
    const before = snapshot(root);
    assert.equal(run(["--check", "0.1.0"], root, sink(), sink()), 0);
    const err = sink();
    assert.equal(run(["--check", "0.1.1"], root, sink(), err), 1);
    assert.match(err.text(), /Cargo\.lock/);
    assert.deepEqual(snapshot(root), before);
  });

  test("파일 문제는 1 로 알린다", () => {
    const root = makeRoot({ "package.json": PACKAGE_JSON });
    const err = sink();
    assert.equal(run(["0.2.0"], root, sink(), err), 1);
    assert.notEqual(err.text(), "");
  });
});

describe("실제 저장소 (읽기만)", () => {
  test("네 파일의 판이 서로 같다 — 손으로 한 곳만 올리면 여기서 걸린다", () => {
    const { version } = JSON.parse(readFileSync(join(REPO, "package.json"), "utf8"));
    assert.deepEqual(versionMismatches(REPO, version), []);
  });

  test("node 로 직접 불러도 잘못된 판은 거절하고 실제 파일을 건드리지 않는다", () => {
    const before = ["package.json", "package-lock.json"].map((f) => readFileSync(join(REPO, f), "utf8"));
    for (const arg of ["v0.2.0", ""]) {
      const result = spawnSync(process.execPath, [SCRIPT, arg], { encoding: "utf8" });
      assert.equal(result.status, 2, `${JSON.stringify(arg)}: ${result.stderr}`);
      assert.match(result.stderr, /SemVer/);
    }
    const none = spawnSync(process.execPath, [SCRIPT], { encoding: "utf8" });
    assert.equal(none.status, 2);
    assert.match(none.stderr, /사용법/);
    const after = ["package.json", "package-lock.json"].map((f) => readFileSync(join(REPO, f), "utf8"));
    assert.deepEqual(after, before);
  });

  test("node 로 직접 --check 하면 맞는 판은 0", () => {
    const { version } = JSON.parse(readFileSync(join(REPO, "package.json"), "utf8"));
    const ok = spawnSync(process.execPath, [SCRIPT, "--check", version], { encoding: "utf8" });
    assert.equal(ok.status, 0, ok.stderr);
    const bad = spawnSync(process.execPath, [SCRIPT, "--check", "99.0.0"], { encoding: "utf8" });
    assert.equal(bad.status, 1);
  });
});

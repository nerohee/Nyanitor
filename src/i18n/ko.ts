/** 조합해 만든 키(예: 시안 막대의 상태 이름)가 정말 있는지 — 없으면 화면에 키를 그대로 보이지 않게 */
export function isTextKey(key: string): key is TextKey {
  return Object.prototype.hasOwnProperty.call(ko, key);
}

export function t(key: TextKey): string {
  return ko[key];
}

/** `{name}` 자리를 채운다. 예: tf("variant.home.used", { n: 42 }) */
export function tf(key: TextKey, vars: Record<string, string | number>): string {
  return ko[key].replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
